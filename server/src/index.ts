import 'dotenv/config';
import express from 'express';
import mongoose from 'mongoose';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import api from './routes/api';
const app = express();
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_ORIGIN || 'http://localhost:4200', credentials: true }));
app.use(express.json({ limit: '32kb' })); app.use(cookieParser());
app.get('/api/v1/health', (_req, res) => res.json({ ok: true, service: 'meditrack-api' }));
app.get('/api/v1/ready', (_req, res) => res.status(mongoose.connection.readyState === 1 ? 200 : 503).json({ ready: mongoose.connection.readyState === 1 }));
app.use('/api/v1/auth', rateLimit({ windowMs: 15 * 60_000, limit: 30, standardHeaders: true, legacyHeaders: false }));
app.use('/api/v1/assistant', rateLimit({ windowMs: 60_000, limit: 10 }));
app.use('/api/v1', api);
app.use((err: any, _req: express.Request, res: express.Response, _next: express.NextFunction) => { if (err?.name === 'ZodError') return res.status(400).json({ error: 'Invalid request.', details: err.issues }); if (err?.code === 11000) return res.status(409).json({ error: 'This record already exists.' }); console.error('Request failed:', err?.message || 'unknown error'); res.status(err?.status || 500).json({ error: err?.status ? err.message : 'An unexpected error occurred.' }); });
const port = Number(process.env.PORT || 3000);
mongoose.connect(process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/meditrack').then(() => app.listen(port, () => console.log(`MediTrack API listening on ${port}`))).catch(err => { console.error('MongoDB connection failed:', err.message); process.exitCode = 1; });
